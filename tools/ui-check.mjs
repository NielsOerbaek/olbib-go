// Drives the UI in WebKit at iPhone size; screenshots each view. Read-only (no borrow/renew/reserve).
import fs from 'node:fs';
import { chromium as webkit, devices } from 'playwright-core';
const OUT = process.argv[2];
const line = fs.readFileSync('capture/traffic.jsonl', 'utf8').split('\n').find((l) => l.includes('identityProviderCallback/borchk') && l.includes('"method":"POST"'));
const p = new URLSearchParams(JSON.parse(line).postData);
const browser = await webkit.launch({ executablePath: '/usr/bin/google-chrome' });
const ctx = await browser.newContext(process.env.DESKTOP ? { viewport: { width: 1000, height: 800 } } : { ...devices['iPhone SE'] });
const page = await ctx.newPage();
const errors = [];
page.on('pageerror', (e) => errors.push('pageerror: ' + e.message));
page.on('console', (m) => m.type() === 'error' && errors.push('console: ' + m.text()));
const shot = async (n) => { await page.waitForTimeout(700); await page.screenshot({ path: `${OUT}/${n}.png` }); };
await page.goto((process.env.BASE ?? 'http://127.0.0.1:3800') + '/');
await page.waitForSelector('#card'); await shot('1-login');
await page.waitForSelector('#site:not([disabled])'); await page.selectOption('#site', process.env.SITE ?? 'kobenhavn'); await page.fill('#card', p.get('loginBibDkUserId')); await page.fill('#pin', p.get('pincode'));
await page.click('button[type=submit]');
await page.waitForSelector('.row, .book', { timeout: 30000 }); await shot('2-loans');
await page.click('#dock a[data-tab=search]'); await page.type('#q', 'wimpy kid', { delay: 60 });
await page.waitForSelector('#hits .row', { timeout: 20000 }); await shot('3-search');
await page.click('.filter[data-type=audiobook]'); await page.waitForTimeout(2500); await shot('3b-filter');
console.log('filtered:', await page.textContent('.count'), (await page.$$eval('#hits .row .chips', (els) => els.slice(0, 5).map((e) => e.textContent.trim().replace(/\s+/g, '/')))).join(' | '));
await page.click('.filter[data-type=""]');
await page.goto((process.env.BASE ?? 'http://127.0.0.1:3800') + '/#/work/' + encodeURIComponent('work-of:870970-basis:61756914'));
await page.waitForSelector('.work-head', { timeout: 20000 }); await shot('4-work'); await page.waitForTimeout(800); await page.screenshot({ path: OUT + '/4-work-full.png', fullPage: true });
await page.goto((process.env.BASE ?? 'http://127.0.0.1:3800') + '/#/');
await page.waitForSelector('a.book[href^="#/listen"]', { timeout: 30000 });
await page.click('a.book[href^="#/listen"]');
await page.waitForSelector('#play'); await page.waitForTimeout(1500); await page.click('#play'); await page.waitForTimeout(3000); await shot('5-listen');
await page.click('#sleep'); await shot('6-sleep'); await page.click('[data-min="15"]'); await shot('7-sleeping');
await page.goto((process.env.BASE ?? 'http://127.0.0.1:3800') + '/#/search'); await page.waitForTimeout(500); await shot('8-mini');
console.log('audio', await page.evaluate(() => { const a = document.querySelector('audio'); return { src: a.src.slice(0, 30), err: a.error?.code ?? null, ready: a.readyState, t: a.currentTime, paused: a.paused, hlsjs: !!window.Hls }; }));
console.log(errors.join('\n') || 'no page errors');
await page.evaluate(() => fetch('/api/logout', { method: 'POST' }));
await browser.close();
